"""Memory store protocol — abstract interface for memory persistence."""
from __future__ import annotations

from typing import Protocol, runtime_checkable

from app.memory.types import ConversationMessage, ConversationSession, Memory


@runtime_checkable
class MemoryStore(Protocol):
    """Protocol for persistent memory storage."""

    def add(self, memory: Memory) -> None: ...
    def get(self, memory_id: str) -> Memory | None: ...
    def search(self, query: str, limit: int = 5) -> list[Memory]: ...
    def delete(self, memory_id: str) -> None: ...
    def all_memories(self, limit: int = 100) -> list[Memory]: ...


@runtime_checkable
class ConversationStore(Protocol):
    """Protocol for conversation persistence."""

    def create_session(self, session: ConversationSession) -> None: ...
    def get_session(self, session_id: str) -> ConversationSession | None: ...
    def update_session_activity(self, session_id: str, timestamp: float) -> None: ...

    def add_message(self, message: ConversationMessage) -> None: ...
    def get_messages(
        self, session_id: str, limit: int = 50
    ) -> list[ConversationMessage]: ...
    def get_message_by_source(self, source_event_id: str) -> ConversationMessage | None: ...
    def clear_session(self, session_id: str) -> None: ...
